package ru.chevteam.onestep.trip;

/**
 * Публичный API О!Плана.
 */
public interface TripPlanner {

    /**
     * Разговор с гостем: либо один уточняющий вопрос, либо до трёх вариантов поездки в бюджете.
     * Сервер не хранит состояние разговора — клиент присылает текст поездки и ответы на вопросы целиком.
     */
    TripPlan plan(TripRequest request);

    /** Пересчитать конкретную поездку после изменения дат, гостей, транспорта или бюджета. */
    TripOption quote(TripQuote request);
}
